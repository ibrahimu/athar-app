// `L10n` و`Recitation` و`AyahAudio` تقرأ `AtharStore.appGroup` لتجد دفاترَ
// المجموعة المشتركة بين التطبيق وودجاته وساعته. والتلفاز ليس منها في شيء: لا
// مجموعةَ تطبيقاتٍ تجمع تلفازًا بهاتف، ولا `AtharStore` في هذا الهدف أصلًا.
//
// فيُعطى الاسمُ ولا يُعطى المخزن: `UserDefaults(suiteName:)` تعود `nil` لمجموعةٍ
// لا يملكها التطبيق، وكلُّ موضعٍ يقرؤها في الملفّات المشتركة يسقط إلى قيمةٍ
// افتراضية سليمة — `?? "system"` في `loc()`، ومعرّفُ قارئٍ محفوظ، وآخرُ سورة.
// ولا يُقرأ شيءٌ من ذلك في واجهة التلفاز، فالسقوطُ لا يُرى.
//
// و`AppConfig.arabicOnly` صادقةٌ على كل حال، فـ`loc()` تُجيب بالعربية قبل أن
// تنظر في الدفاتر أصلًا — فهذا الاسمُ ثابتٌ لا يُستعمل، لا افتراضٌ قد يخيب.
