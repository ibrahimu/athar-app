import Foundation

// MARK: - ما يلزم الملفّاتِ المشتركةَ ولا يوجد على التلفاز
//
// `L10n` و`Recitation` و`AyahAudio` تقرأ `AtharStore.appGroup` لتجد دفاترَ
// المجموعة المشتركة بين التطبيق وودجاته وساعته. والتلفاز ليس منها في شيء: لا
// مجموعةَ تطبيقاتٍ تجمع تلفازًا بهاتف، ولا `AtharStore` في هذا الهدف أصلًا.
//
// فيُعطى الاسمُ ولا يُعطى المخزن: `UserDefaults(suiteName:)` تعود `nil` لمجموعةٍ
// لا يملكها التطبيق، وكلُّ موضعٍ يقرؤها في الملفّات المشتركة يسقط إلى قيمةٍ
// افتراضية سليمة — `?? "system"` في `loc()`، ومعرّفُ قارئٍ محفوظ، وآخرُ سورة.
// ولا يُقرأ شيءٌ من ذلك في واجهة التلفاز، فالسقوطُ لا يُرى.
//
// و`AppConfig.arabicOnly` صادقةٌ على كل حال، فـ`loc()` تُجيب بالعربية قبل أن
// تنظر في الدفاتر أصلًا — فهذا الاسمُ ثابتٌ لا يُستعمل، لا افتراضٌ قد يخيب.
enum AtharStore {
    static let appGroup = "group.com.ibrahim.athar"
}

// MARK: - loc() بلا جدول
//
// `Shared/L10n.swift` ليس في هذا الهدف: جدولُه (١٨٠٤ سطرًا في مُعجمٍ واحد) يُطبق
// مُحسِّنَ Swift في وضع الإصدار — رُصد سبعَ عشرةَ دقيقةً على المعالج كاملًا بلا
// نهاية عند أرشفة التلفاز. والتلفازُ عربيٌّ فقط ولا مفتاحَ لاتينيًّا في ملفّاته
// (grep على الهدف كلِّه)، و`loc()` هناك تُعيد لمفاتيح العربية المفتاحَ نفسه:
// قِيس على الجدول — ١٠٦ مداخل عربية لا واحدةَ منها تختلف عن مفتاحها.
// فهذه مطابقةٌ لا تقريب، وإن عادت الترجماتُ يومًا عاد الملفُّ الأصل.
func loc(_ key: String) -> String { key }

/// نسخةٌ بقوالب: %1$@ و%2$@ … تُستبدل بالوسائط بترتيبها — كما في الأصل حرفًا بحرف.
func loc(_ key: String, _ args: String...) -> String {
    var s = key
    for (i, a) in args.enumerated() {
        s = s.replacingOccurrences(of: "%\(i + 1)$@", with: a)
    }
    return s
}
