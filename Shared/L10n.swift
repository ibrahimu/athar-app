/// لغات واجهة التطبيق. النص الشرعي (القرآن والأذكار) يبقى عربيًا دائمًا —
/// المترجَم هو واجهة الاستخدام فقط.
/// إعدادات عامة للواجهة.
enum AppConfig {
    /// الواجهة عربية فقط حاليًا: مبدّل اللغات مخفي، والاتجاه من اليمين دائمًا.
    /// جداول الترجمة تبقى في مكانها لإعادة التفعيل لاحقًا بقلب هذا العلم.
    static let arabicOnly = true
}

enum AppLanguage: String, CaseIterable, Identifiable {
    case system, ar, en, ur, fa, tr, id, ms, fr, bn

    var id: String { rawValue }

    /// الاسم بلغته هو — كما تعرضه التطبيقات العالمية.
    var title: String {
        switch self {
        case .system: return loc("sysLanguage")
        case .ar: return "العربية"
        case .en: return "English"
        case .ur: return "اردو"
        case .fa: return "فارسی"
        case .tr: return "Türkçe"
        case .id: return "Bahasa Indonesia"
        case .ms: return "Bahasa Melayu"
        case .fr: return "Français"
        case .bn: return "বাংলা"
        }
    }
    var shortTitle: String { title }
    var detail: String { "" }

    /// اللغة الفعلية بعد حلّ «حسب الجهاز».
    var resolved: AppLanguage {
        guard self == .system else { return self }
        for code in Locale.preferredLanguages {
            let p = String(code.prefix(2))
            if let l = AppLanguage(rawValue: p), l != .system { return l }
        }
        return .en
    }

    var isRTL: Bool {
        switch resolved {
        case .ar, .ur, .fa: return true
        default: return false
        }
    }

    var layoutDirection: LayoutDirection { isRTL ? .rightToLeft : .leftToRight }
}

/// الترجمة: مفتاح ← لغة المستخدم، وإلا الإنجليزية، وإلا العربية.
/// القراءة من مجموعة التطبيقات المشتركة لتعمل في الويدجتات أيضًا.
func loc(_ key: String) -> String {
    let stored = UserDefaults(suiteName: AtharStore.appGroup)?
        .string(forKey: "athar.language") ?? "system"
    let lang: AppLanguage = AppConfig.arabicOnly
        ? .ar : (AppLanguage(rawValue: stored) ?? .system).resolved
    if let v = L10nTable.strings[lang.rawValue]?[key] { return v }
    // مفاتيح النصوص عربية أصلًا: في الوضع العربي أعِد المفتاح نفسه بدل السقوط للإنجليزية.
    if lang == .ar { return key }
    return L10nTable.strings["en"]?[key]
        ?? L10nTable.strings["ar"]?[key]
        ?? key
}

/// نسخة بقوالب: القالب يحوي %1$@ و%2$@ … وتُستبدل بالوسائط بترتيبها.
/// يسمح للترجمة بإعادة ترتيب الأرقام (مثل الأردية) دون كسر المعنى.
func loc(_ key: String, _ args: String...) -> String {
    var s = loc(key)
    for (i, a) in args.enumerated() {
        s = s.replacingOccurrences(of: "%\(i + 1)$@", with: a)
    }
    return s
}

